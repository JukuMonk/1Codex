def дерево_и_список_рядом(текст):
    """Группе, в которой лежат дерево и наша колонка, — «всегда
    горизонтально» (так выставил пользователь в EDT): иначе на узком окне
    платформа ставит список под дерево."""
    i = текст.index('<name>мвмКолонкаСписка</name>')
    отступ = len(текст[текст.rfind(СТР, 0, i) + len(СТР):i])
    for м in reversed(list(re.finditer(r'^( *)<name>([^<]+)</name>', текст[:i], re.M))):
        if len(м.group(1)) == отступ - 2:
            break
    else:
        return текст
    н, к = границы(текст, м.group(2))
    кусок = текст[н:к]
    ext = кусок.rfind('<extInfo xsi:type="form:UsualGroupExtInfo">')
    if ext < 0:
        return текст
    конец_строки = кусок.index(СТР, ext) + len(СТР)
    if кусок[конец_строки:].lstrip(' ').startswith('<group>'):
        return текст
    о = ' ' * (len(м.group(1)) + 2)
    кусок = кусок[:конец_строки] + о + '<group>AlwaysHorizontal</group>' + СТР + кусок[конец_строки:]
    return текст[:н] + кусок + текст[к:]


def панель_наверх(текст):
    """Панель поиска — над деревом и списком, во всю ширину формы (так
    пользователь собрал форму настройкой в предприятии, и стало лучше):
    из колонки списка она вынимается и встаёт перед группой, в которой
    лежат дерево и колонка."""
    п = границы(текст, 'мвмПанельПоиска')
    к = границы(текст, 'мвмКолонкаСписка')
    if not п or not к or not (к[0] < п[0] < к[1]):
        return текст
    # родитель колонки — группа «дерево и список»
    i = текст.index('<name>мвмКолонкаСписка</name>')
    отступ_колонки = len(текст[текст.rfind(СТР, 0, i) + len(СТР):i])
    for м in reversed(list(re.finditer(r'^( *)<name>([^<]+)</name>', текст[:i], re.M))):
        if len(м.group(1)) == отступ_колонки - 2:
            break
    else:
        return текст
    родитель = границы(текст, м.group(2))
    # вырезать панель (с переводом строки перед ней). Границы указывают на
    # сам тег <items, поэтому отступ первой строки считаем от начала строки.
    н = текст.rfind(СТР, 0, п[0])
    было = п[0] - (н + len(СТР))
    панель = ' ' * было + текст[п[0]:п[1]]
    текст = текст[:н] + текст[п[1]:]
    # переставить на отступ родителя и вставить перед ним
    надо = len(м.group(1)) - 2
    строки = [с[было - надо:] if с.startswith(' ' * было) else с
              for с in панель.split(СТР)]
    assert строки[0] == ' ' * надо + '<items xsi:type="form:FormGroup">', строки[0]
    родитель = границы(текст, м.group(2))
    н = текст.rfind(СТР, 0, родитель[0]) + len(СТР)
    return текст[:н] + СТР.join(строки) + СТР + текст[н:]


