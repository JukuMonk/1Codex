RU_MANAGER = {'Catalogs': 'Справочники', 'Documents': 'Документы', 'InformationRegisters': 'РегистрыСведений',
              'AccumulationRegisters': 'РегистрыНакопления', 'Constants': 'Константы', 'ExchangePlans': 'ПланыОбмена',
              'ChartsOfCharacteristicTypes': 'ПланыВидовХарактеристик'}
RU_TABLE = {'Catalogs': 'Справочник', 'Documents': 'Документ', 'InformationRegisters': 'РегистрСведений',
            'AccumulationRegisters': 'РегистрНакопления', 'ExchangePlans': 'ПланОбмена',
            'ChartsOfCharacteristicTypes': 'ПланВидовХарактеристик'}


class Сеанс:
    def __init__(self, base):
        self.cn = com.connect(base)

    def в_xml(self, значение):
        w = self.cn.NewObject('ЗаписьXML')
        w.УстановитьСтроку()
        self.cn.XDTOSerializer.ЗаписатьXML(w, значение, self.cn.XMLTypeAssignment.Явное)
        return w.Закрыть()

    def из_xml(self, текст):
        r = self.cn.NewObject('ЧтениеXML')
        r.УстановитьСтроку(текст)
        r.ПерейтиКСодержимому()
        return self.cn.XDTOSerializer.ПрочитатьXML(r)

    def запрос(self, текст):
        з = self.cn.NewObject('Запрос')
        з.Текст = текст
        return з.Выполнить().Выбрать()


def план():
    """Что переносить: свои объекты (из выгрузки ПРОД) и добавленные поля типовых."""
    diff = json.load(open(os.path.join(be.ROOT, 'logs', 'diff.json'), encoding='utf-8'))
    свои = [o.replace('.', '/', 1) for o in diff['new_objects']]
    поля = {}
    for rel in sorted({'/'.join(p.split('/')[:2]).replace('.xml', '') for p in diff['changed'] if p.endswith('.xml')}):
        d = rel.split('/')[0]
        if d not in ('Catalogs', 'Documents', 'ExchangePlans', 'InformationRegisters', 'AccumulationRegisters'):
            continue
        a, _ = diff_meta.children(be.obj_path(be.VENDOR, rel))
        b, _ = diff_meta.children(be.obj_path(be.PROD, rel))
        new = [k for k in sorted(set(b) - set(a)) if k.split('.')[0] in ('Attribute', 'TabularSection', 'Resource', 'Dimension')]
        if new:
            поля[rel] = new
    return свои, поля


# ---------------------------------------------------------------- выгрузка
def выгрузить(base, файл, режим='прод'):
    """режим 'расширение' — тот же снимок из базы с расширением (поля спутников — из регистров-спутников): для сверки."""
    расш = режим == 'расширение'
    с = Сеанс(base)
    свои, поля = план()
    data = {'свои': {}, 'поля': {}, 'спутники': {}}
    t0 = time.time()
    for rel in свои:
        d, имя = rel.split('/')
        if d == 'Catalogs':
            в = с.запрос('ВЫБРАТЬ Т.Ссылка КАК Ссылка ИЗ Справочник.%s КАК Т УПОРЯДОЧИТЬ ПО Т.ЭтоГруппа УБЫВ' % имя
                         if иерархический(rel) else 'ВЫБРАТЬ Т.Ссылка КАК Ссылка ИЗ Справочник.%s КАК Т' % имя)
            data['свои'][rel] = [с.в_xml(в.Ссылка.ПолучитьОбъект()) for _ in iter(в.Следующий, False)]
        elif d == 'Constants':
            data['свои'][rel] = [с.в_xml(getattr(с.cn.Константы, имя).Получить())]
        elif d == 'InformationRegisters':
            data['свои'][rel] = наборы_регистра(с, имя)
        else:
            continue
        print('  %s: %d' % (rel, len(data['свои'][rel])))
    for rel, ключи in поля.items():
        d, имя = rel.split('/')
        if d not in ('Catalogs', 'Documents', 'ExchangePlans'):
            continue                                                      # поля регистров — ниже, спутники
        реквизиты = [k.split('.')[1] for k in ключи if k.startswith('Attribute.')]
        тч = {}
        for k in ключи:
            p = k.split('.')
            if p[0] == 'TabularSection' and len(p) == 4:
                тч.setdefault(p[1], []).append(p[3])
            elif p[0] == 'TabularSection' and len(p) == 2:
                тч.setdefault(p[1], [])                                    # новая ТЧ целиком
        новые_тч = {p.split('.')[1] for p in ключи if p.startswith('TabularSection.') and p.count('.') == 1}
        в = с.запрос('ВЫБРАТЬ Т.Ссылка КАК Ссылка ИЗ %s.%s КАК Т' % (RU_TABLE[d], имя))
        строки = []
        while в.Следующий():
            об = в.Ссылка.ПолучитьОбъект()
            з = {'ref': с.в_xml(в.Ссылка), 'р': {}, 'тч': {}}
            for р in реквизиты:
                v = getattr(об, р)
                if v not in (None, '', 0, False) and not пустая_ссылка(v):
                    з['р'][р] = с.в_xml(v)
            for т, колонки in тч.items():
                таб = getattr(об, т)
                if т in новые_тч:
                    колонки = [к.Имя for к in getattr(с.cn.Метаданные, менеджер_мд(d)).Найти(имя).ТабличныеЧасти.Найти(т).Реквизиты]
                рядки = []
                for i in range(таб.Количество()):
                    стр = таб.Получить(i)
                    рядки.append({к: с.в_xml(getattr(стр, к)) for к in колонки})
                if any(any(not пустое_xml(x) for x in r.values()) for r in рядки):
                    з['тч'][т] = рядки
            if з['р'] or з['тч']:
                строки.append(з)
        data['поля'][rel] = строки
        print('  %s: объектов с данными доработки %d' % (rel, len(строки)))
    # поля типовых регистров → спутники
    data['спутники']['дс_ЦеныНоменклатурыСерий'] = записи_по_регистратору(
        с, 'РегистрСведений.дс_ЦеныНоменклатурыСерий' if расш else 'РегистрСведений.ЦеныНоменклатуры', ('Период', 'Номенклатура', 'ВидЦены', 'Характеристика', 'дс_Серия',
                                                'Цена', 'ЕдиницаИзмерения', 'Валюта'))
    data['спутники']['дс_СверхурочныеТрудозатраты'] = записи_по_регистратору(
        с, 'РегистрНакопления.дс_СверхурочныеТрудозатраты' if расш else 'РегистрНакопления.торо_ФактическиеТрудовыеЗатратыРемонтныхРабот',
        ('Период', 'НомерСтроки', 'Активность', 'РемонтыОборудования_ID', 'Квалификация', 'Сотрудник', 'ID', 'РемонтнаяРабота',
         'торо_ВремяРаботыСверхМенееДвухЧасов', 'торо_ВремяРаботыСверхБолееДвухЧасов', 'торо_ОбщееВремяРаботыСверхГрафика'),
        'Т.торо_ВремяРаботыСверхМенееДвухЧасов <> 0 ИЛИ Т.торо_ВремяРаботыСверхБолееДвухЧасов <> 0 ИЛИ Т.торо_ОбщееВремяРаботыСверхГрафика <> 0',
        все_строки_регистратора=True)
    в = с.запрос('ВЫБРАТЬ Т.ОбъектРемонта КАК ОбъектРемонта, Т.Показатель КАК Показатель, Т.дс_Длинна КАК дс_Длинна '
                 'ИЗ РегистрСведений.%s КАК Т ГДЕ Т.дс_Длинна <> 0' % ('дс_ДлиныИзмеряемыхПоказателей' if расш else 'торо_ИзмеряемыеПоказателиОбъектовРемонта'))
    data['спутники']['дс_ДлиныИзмеряемыхПоказателей'] = [
        {к: с.в_xml(getattr(в, к)) for к in ('ОбъектРемонта', 'Показатель', 'дс_Длинна')} for _ in iter(в.Следующий, False)]
    for k, v in data['спутники'].items():
        print('  спутник %s: %d' % (k, len(v)))
    with open(файл, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False)
    print('выгружено за %.0f с → %s' % (time.time() - t0, файл))
    return 0


def иерархический(rel):
    return '<Hierarchical>true</Hierarchical>' in be.rd(be.obj_path(be.PROD, rel))


def менеджер_мд(d):
    return {'Catalogs': 'Справочники', 'Documents': 'Документы', 'ExchangePlans': 'ПланыОбмена'}[d]


def пустая_ссылка(v):
    try:
        return v.Пустая()
    except Exception:
        return False


def пустое_xml(x):
    return x.endswith('/>') or 'xsi:nil="true"' in x or '>0<' in x and x.count('<') == 2


def наборы_регистра(с, имя):
    """Регистр сведений целиком: независимый — одним набором; подчинённый — наборами по регистраторам."""
    мд = с.cn.Метаданные.РегистрыСведений.Найти(имя)
    менеджер = getattr(с.cn.РегистрыСведений, имя)
    if '<WriteMode>RecorderSubordinate<' in be.rd(be.obj_path(be.PROD, 'InformationRegisters/' + имя)):
        в = с.запрос('ВЫБРАТЬ РАЗЛИЧНЫЕ Т.Регистратор КАК Р ИЗ РегистрСведений.%s КАК Т' % имя)
        out = []
        while в.Следующий():
            н = менеджер.СоздатьНаборЗаписей()
            н.Отбор.Регистратор.Установить(в.Р)
            н.Прочитать()
            out.append(с.в_xml(н))
        return out
    н = менеджер.СоздатьНаборЗаписей()
    н.Прочитать()
    return [с.в_xml(н)] if н.Количество() else []


def записи_по_регистратору(с, таблица, поля, условие=None, все_строки_регистратора=False):
    """{регистратор(xml): [ {поле: xml} ]} — записи регистра; при все_строки_регистратора берутся все строки тех
    регистраторов, у которых хоть одна строка проходит условие (номера строк должны совпасть)."""
    if условие and все_строки_регистратора:
        где = 'ГДЕ Т.Регистратор В (ВЫБРАТЬ РАЗЛИЧНЫЕ Т2.Регистратор ИЗ %s КАК Т2 ГДЕ %s)' % (таблица, условие.replace('Т.', 'Т2.'))
    elif условие:
        где = 'ГДЕ ' + условие
    else:
        где = ''
    в = с.запрос('ВЫБРАТЬ Т.Регистратор КАК Регистратор, %s ИЗ %s КАК Т %s УПОРЯДОЧИТЬ ПО Т.Регистратор, Т.НомерСтроки'
                 % (', '.join('Т.%s КАК %s' % (п, п) for п in поля), таблица, где))
    out = {}
    while в.Следующий():
        out.setdefault(с.в_xml(в.Регистратор), []).append({п: с.в_xml(getattr(в, п)) for п in поля})
    return out


# ---------------------------------------------------------------- подготовка
def подготовить(base):
    """После выгрузки и ДО замены конфигурации: убрать из ЦеныНоменклатуры строки с серией. Без измерения дс_Серия
    они становятся неуникальными, и обновление БД отказывает («Записи регистра сведений стали неуникальными»).
    В расширении цены по сериям живут в дс_ЦеныНоменклатурыСерий (их переносит выгрузка), в типовом — строки без серии,
    ровно как пишет проведение в расширении."""
    с = Сеанс(base)
    в = с.запрос('ВЫБРАТЬ РАЗЛИЧНЫЕ Т.Регистратор КАК Р ИЗ РегистрСведений.ЦеныНоменклатуры КАК Т '
                 'ГДЕ Т.дс_Серия <> ЗНАЧЕНИЕ(Справочник.СерииНоменклатуры.ПустаяСсылка)')
    наборов = строк = 0
    while в.Следующий():
        н = с.cn.РегистрыСведений.ЦеныНоменклатуры.СоздатьНаборЗаписей()
        н.Отбор.Регистратор.Установить(в.Р)
        н.Прочитать()
        for i in reversed(range(н.Количество())):
            if not н.Получить(i).дс_Серия.Пустая():
                н.Удалить(i)
                строк += 1
        н.ОбменДанными.Загрузка = True
        н.Записать(True)
        наборов += 1
    print('ЦеныНоменклатуры: убрано строк с серией %d (регистраторов %d)' % (строк, наборов))
    return 0


# ---------------------------------------------------------------- загрузка
def загрузить(base, файл):
    с = Сеанс(base)
    data = json.load(open(файл, encoding='utf-8'))
    t0 = time.time()
    for rel, items in data['свои'].items():
        d, имя = rel.split('/')
        for x in items:
            v = с.из_xml(x)
            if d == 'Constants':
                getattr(с.cn.Константы, имя).Установить(v)
                continue
            if d == 'Catalogs' and v.ИмяПредопределенныхДанных:
                # предопределённые расширение уже создало со своими ссылками — заменяем их элементами ПРОД
                з = с.cn.NewObject('Запрос')
                з.Текст = ('ВЫБРАТЬ Т.Ссылка КАК Ссылка ИЗ Справочник.%s КАК Т '
                           'ГДЕ Т.ИмяПредопределенныхДанных = &Имя И Т.Ссылка <> &Ссылка' % имя)
                з.УстановитьПараметр('Имя', v.ИмяПредопределенныхДанных)
                з.УстановитьПараметр('Ссылка', v.Ссылка)
                в = з.Выполнить().Выбрать()
                while в.Следующий():
                    лишний = в.Ссылка.ПолучитьОбъект()
                    лишний.ОбменДанными.Загрузка = True
                    лишний.Удалить()
            v.ОбменДанными.Загрузка = True
            v.Записать()
        print('  %s: %d' % (rel, len(items)))
    for rel, строки in data['поля'].items():
        for з in строки:
            об = с.из_xml(з['ref']).ПолучитьОбъект()
            if об is None:
                print('  нет объекта', rel)
                continue
            for р, x in з['р'].items():
                setattr(об, р, с.из_xml(x))
            for т, рядки in з['тч'].items():
                таб = getattr(об, т)
                if таб.Количество() < len(рядки):
                    for _ in range(len(рядки) - таб.Количество()):
                        таб.Добавить()
                for i, рядок in enumerate(рядки):
                    стр = таб.Получить(i)
                    for к, x in рядок.items():
                        setattr(стр, к, с.из_xml(x))
            об.ОбменДанными.Загрузка = True
            об.Записать()
        print('  %s: %d' % (rel, len(строки)))
    for рег in ('дс_ЦеныНоменклатурыСерий',):
        for рег_xml, записи in data['спутники'][рег].items():
            н = getattr(с.cn.РегистрыСведений, рег).СоздатьНаборЗаписей()
            н.Отбор.Регистратор.Установить(с.из_xml(рег_xml))
            for з in записи:
                стр = н.Добавить()
                for к, x in з.items():
                    setattr(стр, к, с.из_xml(x))
            н.ОбменДанными.Загрузка = True
            н.Записать(True)
        print('  спутник %s: регистраторов %d' % (рег, len(data['спутники'][рег])))
    рег = 'дс_СверхурочныеТрудозатраты'
    for рег_xml, записи in data['спутники'][рег].items():
        н = getattr(с.cn.РегистрыНакопления, рег).СоздатьНаборЗаписей()
        н.Отбор.Регистратор.Установить(с.из_xml(рег_xml))
        for з in записи:
            стр = н.Добавить()
            for к, x in з.items():
                if к != 'НомерСтроки':
                    setattr(стр, к, с.из_xml(x))
        н.ОбменДанными.Загрузка = True
        н.Записать(True)
    print('  спутник %s: регистраторов %d' % (рег, len(data['спутники'][рег])))
    н = с.cn.РегистрыСведений.дс_ДлиныИзмеряемыхПоказателей
    for з in data['спутники']['дс_ДлиныИзмеряемыхПоказателей']:
        м = н.СоздатьМенеджерЗаписи()
        for к, x in з.items():
            setattr(м, к, с.из_xml(x))
        м.Записать(True)
    print('  спутник дс_ДлиныИзмеряемыхПоказателей: %d' % len(data['спутники']['дс_ДлиныИзмеряемыхПоказателей']))
    print('загружено за %.0f с' % (time.time() - t0))
    return 0


if __name__ == '__main__':
    a = sys.argv[1:]
    if len(a) in (3, 4) and a[0] == 'выгрузить':
        sys.exit(выгрузить(*a[1:]))
    if len(a) == 2 and a[0] == 'подготовить':
        sys.exit(подготовить(a[1]))
    if len(a) == 3 and a[0] == 'загрузить':
        sys.exit(загрузить(a[1], a[2]))
    sys.exit(__doc__)
