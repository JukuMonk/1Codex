def объектный_набор(текст, имя):
    """Набор-запрос → внешний набор (DataSetObject «имя»): ПроцессорКомпоновкиДанных.Инициализировать получает
    таблицу значений под этим именем (пульс_Отчеты.Скомпоновать)."""
    текст, n = re.subn(r'<dataSet xsi:type="DataSetQuery">', '<dataSet xsi:type="DataSetObject">', текст, count=1)
    assert n == 1
    текст, n = re.subn(r'(\t\t<dataSource>ИсточникДанных1</dataSource>)\r?\n\t\t<query>.*?</query>',
                       lambda m: m.group(1) + '\r\n\t\t<objectName>%s</objectName>' % имя, текст, count=1, flags=re.S)
    assert n == 1
    return текст


def скрыть_параметры(текст, имена):
    """Служебные параметры (НачалоUTC…) — без права изменения пользователем (useRestriction=true)."""
    for имя in имена:
        текст, n = re.subn(r'(<parameter>\s*<name>%s</name>.*?<useRestriction>)false(</useRestriction>)' % имя,
                           r'\g<1>true\g<2>', текст, count=1, flags=re.S)
        assert n == 1, имя
    return текст


def таблица_по_дням(текст, вариант, строки, колонка, ресурсы, оформление):
    """Структура варианта — таблица: строки по `строки`, колонки по `колонка` (вместо групп dcs_schema_ex)."""
    o = '\t\t\t'

    def группа(тег, поле):
        return ([o + '\t<dcsset:%s>' % тег, o + '\t\t<dcsset:groupItems>'] +
                [x.replace(o, o + '\t\t\t', 1) for x in el._dcs_group_field(поле, o)] +
                [o + '\t\t</dcsset:groupItems>', o + '\t\t<dcsset:order>', o + '\t\t\t<dcsset:item xsi:type="dcsset:OrderItemAuto"/>',
                 o + '\t\t</dcsset:order>', o + '\t\t<dcsset:selection>', o + '\t\t\t<dcsset:item xsi:type="dcsset:SelectedItemAuto"/>',
                 o + '\t\t</dcsset:selection>', o + '\t</dcsset:%s>' % тег])
    таблица = [o + '<dcsset:item xsi:type="dcsset:StructureItemTable">'] + группа('column', колонка)
    for поле in строки:
        таблица += группа('row', поле)
    таблица += [o + '</dcsset:item>']
    # заменить структуру варианта (последний элемент перед </dcsset:settings> этого варианта)
    начало = текст.index('<dcsset:name>%s</dcsset:name>' % вариант)
    конец = текст.index('\t\t</dcsset:settings>', начало)
    кусок = текст[начало:конец]
    i = кусок.rindex('</dcsset:outputParameters>') + len('</dcsset:outputParameters>')
    кусок = кусок[:i] + '\r\n' + '\r\n'.join(таблица) + '\r\n'
    # выбор — только ресурсы ячейки; условное оформление ячеек
    кусок = re.sub(r'<dcsset:selection>.*?</dcsset:selection>', lambda m: '<dcsset:selection>\r\n' + '\r\n'.join(
        o + '\t<dcsset:item xsi:type="dcsset:SelectedItemField">\r\n' + o + '\t\t<dcsset:field>%s</dcsset:field>\r\n' % р +
        o + '\t</dcsset:item>' for р in ресурсы) + '\r\n' + o + '</dcsset:selection>', кусок, count=1, flags=re.S)
    if оформление:
        ca = '\r\n'.join(el._dcs_ca(оформление, o))
        кусок = кусок.replace(o + '<dcsset:outputParameters>', ca + '\r\n' + o + '<dcsset:outputParameters>', 1)
    return текст[:начало] + кусок + текст[конец:]


def формат_вычисляемого(текст, поле, формат):
    """Формат вычисляемого поля (dcs_schema_ex его не задаёт): appearance после title, как у полей набора."""
    i = текст.index('<dataPath>%s</dataPath>' % поле, текст.index('<calculatedField>'))
    j = текст.index('</title>', i) + len('</title>')
    блок = ('\r\n\t\t<appearance>\r\n\t\t\t<dcscor:item xsi:type="dcsset:SettingsParameterValue">\r\n'
            '\t\t\t\t<dcscor:parameter>Формат</dcscor:parameter>\r\n' +
            '\r\n'.join(el._local_string('dcscor:value', формат, '\t\t\t\t')) +
            '\r\n\t\t\t</dcscor:item>\r\n\t\t</appearance>')
    return текст[:j] + блок + текст[j:]


def шкала_загрузки(поле, цель=65):
    """Цвет фона по загрузке: как тепловая карта панели (зелёный — у цели и выше, оранжевый — далеко ниже)."""
    return [
        CA([поле], [(поле, 'GreaterOrEqual', цель)], {'ЦветФона': '#CDEBD3', 'ЦветТекста': ЗЕЛЁНЫЙ}, 'загрузка ≥ цели'),
        CA([поле], [(поле, 'Less', цель), (поле, 'GreaterOrEqual', цель * 0.75)], {'ЦветФона': '#FFF3D1'},
           'загрузка немного ниже цели'),
        CA([поле], [(поле, 'Less', цель * 0.75), (поле, 'Greater', 0)], {'ЦветФона': '#FDE2CC', 'ЦветТекста': ОРАНЖЕВЫЙ},
           'загрузка значительно ниже цели'),
    ]


