def завести_константу():
    папка = os.path.join(ИСХ, 'Constants', КОНСТАНТА)
    путь = os.path.join(папка, КОНСТАНТА + '.mdo')
    текст = СТР.join(КОНСТАНТА_MDO)
    сделано = []
    if not os.path.exists(путь) or база.прочитать(путь) != текст:
        if not база.ПРОБА:
            os.makedirs(папка, exist_ok=True)
            io.open(путь, 'wb').write(текст.encode('utf-8'))
        сделано.append('описание')
    конф = os.path.join(ИСХ, 'Configuration', 'Configuration.mdo')
    т = база.прочитать(конф)
    строка = '  <constants>Constant.%s</constants>' % КОНСТАНТА
    if строка + СТР not in т:
        последняя = т.rfind('  <constants>')
        конец = т.index(СТР, последняя) + len(СТР)
        if not база.ПРОБА:
            io.open(конф, 'wb').write((т[:конец] + строка + СТР + т[конец:]).encode('utf-8'))
        сделано.append('регистрация в конфигурации')
    return сделано


