def прочитать(путь):
    сырьё = open(путь, 'rb').read()
    if сырьё.startswith(b'\xef\xbb\xbf'):
        sys.exit('ОШИБКА: у %s появился BOM' % путь)
    return сырьё.decode('utf-8')


def записать(путь, текст):
    if текст.count('\n') != текст.count(СТР):
        sys.exit('ОШИБКА: %s не в CRLF' % путь)
    if путь.endswith('.form'):
        try:
            ET.fromstring(текст.encode('utf-8'))
        except ET.ParseError as e:
            sys.exit('ОШИБКА: %s не разбирается: %s' % (путь, e))
    if not ПРОБА:
        open(путь, 'wb').write(текст.encode('utf-8'))


class Счётчик(object):
    def __init__(self, старт):
        self.n = старт

    def __call__(self):
        self.n += 1
        return self.n - 1


def поле_поиска(сч, имя, подпись, отступ):
    """Поле поиска: как обычное поле ввода, но с обработчиком изменения."""
    # Ширина задана: с автошириной поля растягивались на всю форму и
    # уезжали вправо. Кнопка очистки — сброс отбора одним касанием.
    строки = образец.поле(сч, имя, имя, отступ, 'InputField', подпись,
                          ширина=22)
    о = ' ' * отступ
    место = строки.index('%s    <wrap>true</wrap>' % о) + 1
    строки[место:место] = ['%s    <clearButton>true</clearButton>' % о]
