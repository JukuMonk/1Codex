def правка_модуля(текст):
    исходный = текст
    # умолчания нового заказа — под константой
    if СТАРЫЕ_ВИДЫ in текст:
        текст = текст.replace(СТАРЫЕ_ВИДЫ, НОВЫЕ_ВИДЫ, 1)
    elif ПРЕЖНИЕ_ВИДЫ in текст:
        текст = текст.replace(ПРЕЖНИЕ_ВИДЫ, НОВЫЕ_ВИДЫ, 1)
    elif НОВЫЕ_ВИДЫ not in текст:
        if текст.count(ЯКОРЬ_ВИДЫ) != 1:
            sys.exit('ОШИБКА: в модуле не найден блок вида доставки по настройкам пользователя')
        текст = текст.replace(ЯКОРЬ_ВИДЫ, ЯКОРЬ_ВИДЫ + НОВЫЕ_ВИДЫ, 1)
    if СТАРАЯ_ДЕТАЛИЗАЦИЯ in текст:
        текст = текст.replace(СТАРАЯ_ДЕТАЛИЗАЦИЯ, НОВАЯ_ДЕТАЛИЗАЦИЯ, 1)
    elif НОВАЯ_ДЕТАЛИЗАЦИЯ not in текст:
        if текст.count(ЯКОРЬ_ДЕТАЛИЗАЦИЯ) != 1:
            sys.exit('ОШИБКА: в модуле не найден блок детализации по умолчанию')
        текст = текст.replace(ЯКОРЬ_ДЕТАЛИЗАЦИЯ, ЯКОРЬ_ДЕТАЛИЗАЦИЯ + НОВАЯ_ДЕТАЛИЗАЦИЯ, 1)
    if ЗАКАЗЧИК not in текст:
        # прежняя редакция без настройки пользователя — убираем
        н = текст.find(ТАБ + '// Упрощённая форма заявки: новый заказ — от подразделения')
        if н >= 0:
            # прежний блок — до якоря: организации в нём могло и не быть
            к = текст.index(ЯКОРЬ_ЗАКАЗЧИК, н)
            текст = текст[:н] + текст[к:]
        if текст.count(ЯКОРЬ_ЗАКАЗЧИК) != 1:
            sys.exit('ОШИБКА: в модуле не найден разбор типа заказчика')
        текст = текст.replace(ЯКОРЬ_ЗАКАЗЧИК, ЗАКАЗЧИК + ЯКОРЬ_ЗАКАЗЧИК, 1)
    # процедуры — в конец модуля (перезаписываются целиком: список «лишнего» растёт)
    if ШАПКА_ПРОЦЕДУР in текст:
        н = текст.index(ШАПКА_ПРОЦЕДУР)
        к = текст.index('Процедура мвмСкрытьЛишнее()')
        к = текст.index('КонецПроцедуры', к) + len('КонецПроцедуры') + len(СТР)
        текст = текст[:н] + ПРОЦЕДУРЫ + текст[к:]
    else:
        текст = текст.rstrip(СТР) + СТР + СТР + ПРОЦЕДУРЫ
    текст = база.вставить_в_процедуру(текст, 'ПриСозданииНаСервере',
                                      ТАБ + 'мвмУпроститьФорму();', False)
    текст = база.вставить_в_процедуру(текст, 'УстановитьВидимость',
                                      ТАБ + 'мвмСкрытьЛишнее();', False)
    for имя, сторона in (('НайтиНаКартеАдресОтправления', 'Истина'),
                         ('НайтиНаКартеАдресНазначения', 'Ложь')):
        текст = база.вставить_в_процедуру(текст, имя, СТР.join([
            ТАБ + 'Если мвмУпрощённаяФормаЗаявки() Тогда',
            ТАБ * 2 + 'мвмВыбратьПунктНаКарте(%s);' % сторона,
            ТАБ * 2 + 'Возврат;',
            ТАБ + 'КонецЕсли;']), True)
    return текст, текст != исходный


