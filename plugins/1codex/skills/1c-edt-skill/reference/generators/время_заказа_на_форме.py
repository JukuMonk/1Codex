def правка_формы(текст):
    if 'мвмГруппаРасчёт' in текст and '<name>мвмОтправлениеСЧ</name>' in текст:
        return дополнить_расчёт(текст)

    # 1. Старые группы в начале формы — долой: соберём заново на месте.
    текст = вырезать(текст, 'мвмГруппаРасчёта')
    текст = вырезать(текст, 'мвмГруппаВремяВПути')

    сч = Счётчик(max(int(ч) for ч in re.findall(r'<id>(\d+)</id>', текст)) + 1)
    рекв = [int(м.group(1)) for м in re.finditer(r'<attributes>.*?<id>(\d+)</id>', текст, re.S)]
    номер = max(рекв) + 1
    новые_реквизиты = []

    # 2. Ч:М:С у четырёх дат: поле часа скрыть, после поля дня — три поля.
    for рекв_имя, поле_час, поле_день, _обр in ДАТЫ:
        текст = скрыть(текст, поле_час)
        н, к = элемент(текст, поле_день)
        отступ = отступ_строки(текст, н)
        части = []
        for буква, подпись, _вес in ЧАСТИ:
            имя = 'мвм%s%s' % (рекв_имя, буква)
            if ('<name>%s</name>' % имя) not in текст:
                новые_реквизиты += реквизит_числа(имя, подпись, номер)
                номер += 1
            части += поле_с_обработчиком(сч, имя, подпись, отступ,
                                         'мвмЧастьВремениПриИзменении')
        текст = текст[:к] + СТР + СТР.join(части) + текст[к:]

    # 3. Строка расчёта под блоками отправления и прибытия.
    for _р, поле, _п, _о, _в in СТОЯНКИ:
        текст = скрыть(текст, поле)
    # Типовая группа вокруг надписи «Общая стоянка» и скрытого поля — тоже
    # прочь (так сделал пользователь в EDT): иначе остаётся пустая строка.
    for надпись in ('ОбщаяСтоянкаПунктОтправления', 'ОбщаяСтоянкаПунктНазначения'):
        текст = скрыть(текст, родитель(текст, надпись))
    н, к = элемент(текст, 'ГруппаОсновноеКолонки')
    отступ = отступ_строки(текст, н)
    содержимое = кнопка_расчёта(сч, отступ + 2)
    в_пути = []
    for буква, подпись, _вес in ЧАСТИ:
        имя = 'мвмВПути' + буква
        if ('<name>%s</name>' % имя) not in текст:
            новые_реквизиты += реквизит_числа(имя, подпись, номер)
            номер += 1
        # Подпись группы несёт ПЕРВОЕ поле, сама группа без заголовка — как
        # типовая «ГруппаОтправлениеС»: тогда платформа ставит подпись в общую
        # колонку подписей, а поля сразу за ней. С заголовком группы поля
        # уезжали к правому краю.
        в_пути += поле_части(сч, имя, ('Время в пути, ' + подпись) if буква == 'Ч' else подпись,
                             отступ + 4, только_чтение=True)
    содержимое += группа(сч, 'мвмГруппаВремяВПути', 'Время в пути', в_пути, отступ + 2,
                         вид='AlwaysHorizontal', показывать_заголовок=False)
    for рекв_имя, _поле, подпись_группы, _обр, вид_группы in СТОЯНКИ:
        части = []
        for буква, подпись, _вес in ЧАСТИ:
            имя = 'мвм%s%s' % (рекв_имя, буква)
            if ('<name>%s</name>' % имя) not in текст:
                новые_реквизиты += реквизит_числа(имя, подпись, номер)
                номер += 1
            подпись_поля = ('Стоянка: %s, %s' % (подпись_группы.lower(), подпись)
                            if буква == 'Ч' else подпись)
            части += поле_с_обработчиком(сч, имя, подпись_поля, отступ + 4,
                                         'мвмЧастьСтоянкиПриИзменении')
        содержимое += группа(сч, 'мвмГруппаСтоянка' + рекв_имя,
                             'Стоянка: ' + подпись_группы.lower(), части, отступ + 2,
                             вид=вид_группы, показывать_заголовок=False)
    содержимое += группа_пути(сч, отступ + 2)
    строка = группа(сч, 'мвмГруппаРасчёт', 'Расчёт по плану завода', содержимое,
                    отступ, вид='Vertical')
    текст = текст[:к] + СТР + СТР.join(строка) + текст[к:]

    # 4. Реквизиты — перед первым <attributes>.
    if новые_реквизиты:
        i = текст.index(СТР + '  <attributes>') + len(СТР)
        текст = текст[:i] + СТР.join(новые_реквизиты) + СТР + текст[i:]
    return текст, True


