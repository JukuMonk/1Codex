def желаемое_время(текст):
    изменено = False
    for имя, перед in ЖЕЛАЕМОЕ:
        if ('<name>%s</name>' % имя) in текст:
            continue
        сч = база.Счётчик(max(int(ч) for ч in re.findall('<id>([0-9]+)</id>', текст)) + 1)
        н, _ = база.элемент(текст, перед)
        о = ' ' * отступ(текст, н)
        i = текст.rfind(СТР, 0, н) + len(СТР)
        текст = текст[:i] + СТР.join(надпись(сч, имя, 'Желаемое время', о)) + СТР + текст[i:]
        изменено = True
    return текст, изменено


def белый_фон(текст):
    """Поле только для чтения платформа рисует без фона — на зелёной подложке
    цифры сливаются. Белый фон возвращает им вид поля."""
    изменено = False
    for имя in ТОЛЬКО_ЧТЕНИЕ:
        н, к = база.элемент(текст, имя)
        кусок = текст[н:к]
        if '<backColor' in кусок:
            continue
        якорь = '<textEdit>true</textEdit>'
        i = кусок.index(якорь) + len(якорь)
        о = ' ' * (отступ(текст, н) + 4)
        кусок = (кусок[:i] + СТР + о + '<backColor xsi:type="core:ColorDef">' + СТР
                 + о + '  <red>255</red>' + СТР + о + '  <green>255</green>' + СТР
                 + о + '  <blue>255</blue>' + СТР + о + '</backColor>' + кусок[i:])
        текст = текст[:н] + кусок + текст[к:]
        изменено = True
    return текст, изменено


def оформить_группу_расчёта(текст):
    """Как «Отправление»: WeakSeparation и зелёная подложка."""
    н, к = база.элемент(текст, 'мвмГруппаРасчёт')
    кусок = текст[н:к]
    ext = кусок.rfind('<extInfo xsi:type="form:UsualGroupExtInfo">')
    конец = кусок.index('</extInfo>', ext)
    if '<backColor' in кусок[ext:конец]:
        return текст, False
    о = ' ' * (отступ(текст, н) + 4)
    строки = [с for с in кусок[ext:конец].split(СТР)[1:] if с.strip()]

    def после(тег, новые):
        for i, с in enumerate(строки):
            if с.strip().startswith('<' + тег + '>'):
                строки[i + 1:i + 1] = новые
                return
        строки[0:0] = новые

    после('horizontalAlign', [о + '<representation>WeakSeparation</representation>'])
    после('showTitle', [о + '<backColor xsi:type="core:ColorDef">',
                        о + '  <red>242</red>', о + '  <green>255</green>',
                        о + '  <blue>242</blue>', о + '</backColor>'])
    кусок = (кусок[:ext] + '<extInfo xsi:type="form:UsualGroupExtInfo">' + СТР
             + СТР.join(строки) + СТР + о[:-2] + кусок[конец:])
    return текст[:н] + кусок + текст[к:], True


def кнопка_с_картинкой(текст):
    н, к = база.элемент(текст, 'мвмРассчитатьВремя')
    кусок = текст[н:к]
    изменено = False
    if '<picture' not in кусок:
        якорь = '<placementArea>UserCmds</placementArea>'
        i = кусок.index(якорь) + len(якорь)
        о = ' ' * (отступ(текст, н) + 2)
        кусок = (кусок[:i] + СТР + о + '<picture xsi:type="core:PictureRef">' + СТР
                 + о + '  <picture>' + КАРТИНКА + '</picture>' + СТР + о + '</picture>'
                 + кусок[i:])
        кусок = кусок.replace('<representation>Auto</representation>',
                              '<representation>PictureAndText</representation>', 1)
        текст = текст[:н] + кусок + текст[к:]
        изменено = True
    # заголовок команды формы — его и показывает кнопка
    i = текст.index('<formCommands>')
    j = текст.index('<name>мвмРассчитатьВремя</name>', i)
    старое = текст.index('<value>', j)
    конец = текст.index('</value>', старое)
    if текст[старое + 7:конец] != ЗАГОЛОВОК_КНОПКИ:
        текст = текст[:старое + 7] + ЗАГОЛОВОК_КНОПКИ + текст[конец:]
        изменено = True
    return текст, изменено


def правка_формы(текст):
    исходный = текст
    for шаг in (вернуть_типовую_раскладку, желаемое_время, белый_фон,
                оформить_группу_расчёта, кнопка_с_картинкой):
        текст, _ = шаг(текст)
    return текст, текст != исходный


