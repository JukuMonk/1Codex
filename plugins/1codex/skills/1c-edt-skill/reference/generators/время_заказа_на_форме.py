def ТИПОВЫЕ_СВОЙСТВА_ГРУППЫ(о, показывать_заголовок):
    """Четыре свойства, которые типовая пишет у КАЖДОЙ группы. Без них EDT
    отдаёт в платформу «сквозное выравнивание: использовать», и элементы
    строки расчёта разъезжаются по колонкам всей страницы: «ч» у подписи,
    «мин/сек» у правого края. Порядок тегов — как у типовой."""
    return (['%s    <showLeftMargin>true</showLeftMargin>' % о,
             '%s    <united>true</united>' % о]
            + (['%s    <showTitle>true</showTitle>' % о] if показывать_заголовок else [])
            + ['%s    <throughAlign>Auto</throughAlign>' % о,
               '%s    <currentRowUse>Auto</currentRowUse>' % о])


def группа(сч, имя, заголовок, содержимое, отступ, вид=None, показывать_заголовок=True):
    """Группа с заголовком. «вид» — AlwaysHorizontal / Vertical / None:
    None значит умолчание EDT (Horizontal), и тег тогда не пишется — так
    сохраняет сам EDT, а значения по умолчанию (representation None)
    он опускает. Раскладка снята с формы, поправленной пользователем."""
    о = ' ' * отступ
    строки = ['%s<items xsi:type="form:FormGroup">' % о,
              '%s  <name>%s</name>' % (о, имя),
              '%s  <id>%d</id>' % (о, сч())]
    строки += содержимое
    строки += ['%s  <visible>true</visible>' % о,
               '%s  <enabled>true</enabled>' % о,
               '%s  <userVisible>' % о,
               '%s    <common>true</common>' % о,
               '%s  </userVisible>' % о,
               '%s  <title>' % о,
               '%s    <key>ru</key>' % о,
               '%s    <value>%s</value>' % (о, заголовок),
               '%s  </title>' % о]
    строки += образец.подсказка(имя, сч(), отступ + 2)
    строки += ['%s  <type>UsualGroup</type>' % о,
               '%s  <extInfo xsi:type="form:UsualGroupExtInfo">' % о,
               ] + (['%s    <group>%s</group>' % (о, вид)] if вид else []) + [
               '%s    <horizontalAlign>Left</horizontalAlign>' % о,
               ] + ТИПОВЫЕ_СВОЙСТВА_ГРУППЫ(о, показывать_заголовок) + [
               '%s  </extInfo>' % о,
               '%s</items>' % о]
    return строки


