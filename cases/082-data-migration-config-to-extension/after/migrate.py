"""Перенос ДАННЫХ доработок при переходе «ПРОД (доработанная конфигурация)» → «поставка 3.0.8.1 + расширение».

При замене конфигурации на типовую реструктуризация удаляет колонки новых реквизитов типовых объектов и таблицы
объектов дс_*; в расширении это другие объекты метаданных (новые таблицы). Поэтому:

  1. выгрузить (в базе со старой конфигурацией ПРОД):   python tools/migrate.py выгрузить <база> <файл.json>
  1а. подготовить (там же, сразу после выгрузки):       python tools/migrate.py подготовить <база>
  2. загрузить поставку 3.0.8.1, обновить БД, подключить расширение НПЦАП_Доработки (tools/ext_activate.py);
  3. загрузить (в базе с расширением):                  python tools/migrate.py загрузить <база> <файл.json>

Что переносится (значения — через XDTOСериализатор, ссылки сохраняют уникальные идентификаторы):
  * свои объекты дс_*: справочники, константы, регистры сведений (наборы целиком / по регистратору);
  * новые реквизиты и ТЧ типовых объектов (по ссылке объекта, в режиме ОбменДанными.Загрузка — без проведения);
  * поля типовых регистров, ушедшие в регистры-спутники: ЦеныНоменклатуры.дс_Серия → дс_ЦеныНоменклатурыСерий,
    сверхурочные трудозатраты → дс_СверхурочныеТрудозатраты (по регистратору и номеру строки),
    торо_ИзмеряемыеПоказателиОбъектовРемонта.дс_Длинна → дс_ДлиныИзмеряемыхПоказателей.
"""
