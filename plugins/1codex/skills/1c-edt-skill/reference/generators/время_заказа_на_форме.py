def конец_элемента(текст, начало):
    """Позиция сразу после </items>, закрывающего элемент с этого начала."""
    глубина = 0
    p = начало
    while True:
        откр = текст.find('<items xsi:type=', p + 1)
        закр = текст.find('</items>', p + 1)
        if закр < 0:
            sys.exit('ОШИБКА: элемент не закрыт')
        if откр < 0 or закр < откр:
            if глубина == 0:
                return закр + len('</items>')
            глубина -= 1
            p = закр
        else:
            глубина += 1
            p = откр


def элемент(текст, имя):
    """(начало, конец) элемента формы по имени."""
    метка = '<name>%s</name>' % имя
    i = текст.find(метка)
    if i < 0:
        sys.exit('ОШИБКА: на форме нет элемента %s' % имя)
    начало = текст.rfind('<items xsi:type=', 0, i)
    return начало, конец_элемента(текст, начало)


def отступ_строки(текст, позиция):
    н = текст.rfind(СТР, 0, позиция) + len(СТР)
    return len(текст[н:позиция]) - len(текст[н:позиция].lstrip(' '))


