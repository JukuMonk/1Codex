# Команда открытия у каждого вида объекта своя: у обработки — Open, у списков
# справочников и регистров — OpenList. Перечисления в панель навигации не
# попадают вовсе, поэтому в порядке их нет.
КОМАНДА = {'Catalog': 'StandardCommand.OpenList',
           'Document': 'StandardCommand.OpenList',
           'InformationRegister': 'StandardCommand.OpenList',
           'DataProcessor': 'StandardCommand.Open',
           'Report': 'StandardCommand.Open',
           'Constant': 'StandardCommand.Open'}


def команды_группы(состав):
    """Команды списков в порядке состава; чего в интерфейсе нет — пропускаем."""
    итог = []
    for объект in состав:
        вид = объект.split('.', 1)[0]
        if вид in КОМАНДА:
            итог.append('%s.%s' % (объект, КОМАНДА[вид]))
    return итог


def описание_интерфейса(команды, важные=(), подсистемы=()):
    строки = ['<?xml version="1.0" encoding="UTF-8"?>',
              '<cmi:CommandInterface xmlns:cmi="http://g5.1c.ru/v8/dt/cmi">']
    if важные or команды:
        строки.append('  <commandsOrder>')
        for группа_панели, список in (('NavigationPanelImportant', важные),
                                      ('NavigationPanelOrdinary', команды)):
            if not список:
                continue
            строки.append('    <orderFragments>')
            строки.append('      <group>%s</group>' % группа_панели)
            for команда in список:
                строки.append('      <commands>%s</commands>' % команда)
            строки.append('    </orderFragments>')
        строки.append('  </commandsOrder>')
    if подсистемы:
        строки.append('  <subsystemsOrder>')
        for имя in подсистемы:
            строки.append('    <subsystems>Subsystem.%s.Subsystem.%s</subsystems>'
                          % (ИМЯ, имя))
        строки.append('  </subsystemsOrder>')
    строки += ['</cmi:CommandInterface>', '']
    return '\r\n'.join(строки)


