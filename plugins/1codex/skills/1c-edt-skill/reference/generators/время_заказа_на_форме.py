def вставить_в_процедуру(текст, имя, строка, в_начало):
    """Строка в тело процедуры: в начало (после объявления) или в конец
    (перед КонецПроцедуры). Уже есть — не трогаем."""
    м = re.search(r'^Процедура %s\(.*?\)\s*$' % re.escape(имя), текст, re.M)
    if not м:
        sys.exit('ОШИБКА: в модуле нет процедуры %s' % имя)
    начало = м.end()
    конец = текст.index(СТР + 'КонецПроцедуры', начало)
    тело = текст[начало:конец]
    if строка.strip() in тело:
        return текст
    if в_начало:
        # регулярное выражение объявления съедает CR перед LF — вставляем
        # за целым переводом строки, иначе в модуле остаётся одиночный LF
        за_объявлением = текст.index(СТР, м.start()) + len(СТР)
        return текст[:за_объявлением] + строка + СТР + текст[за_объявлением:]
    # Последний оператор типовой процедуры может стоять без «;» — перед
    # КонецПроцедуры это законно. Наш вызов после него требует «;».
    хвост = тело.rstrip()
    последняя = [с for с in хвост.split(СТР) if с.strip() and not с.strip().startswith('//')]
    if последняя and not последняя[-1].rstrip().endswith(';'):
        тело_с_точкой = тело.rstrip() + ';' + тело[len(тело.rstrip()):]
        текст = текст[:начало] + тело_с_точкой + текст[конец:]
        конец = текст.index(СТР + 'КонецПроцедуры', начало)
    return текст[:конец] + СТР + строка + текст[конец:]


def дополнить_выбор_по_складу(текст):
    """Модуль прежней сборки: функция начала выбора и её вызовы."""
    исходный = текст
    if 'Функция мвмНачалоВыбораПункта(' not in текст:
        н = МОДУЛЬ.index('// Форму выбора пункта типовая открывает сама')
        к = МОДУЛЬ.index('&НаКлиенте' + '\n' + 'Процедура мвмСкладВыбран(Сторона)')
        кусок = МОДУЛЬ[н:к].replace('\n', СТР)
        якорь = СТР + '&НаКлиенте' + СТР + 'Процедура мвмСкладВыбран(Сторона)'
        if текст.count(якорь) != 1:
            sys.exit('ОШИБКА: в модуле не найдена мвмСкладВыбран')
        текст = текст.replace(якорь, СТР + кусок + '&НаКлиенте' + СТР + 'Процедура мвмСкладВыбран(Сторона)', 1)
    for имя, строка, в_начало in ВСТАВКИ:
        if 'НачалоВыбора' in имя:
            текст = вставить_в_процедуру(текст, имя, строка, в_начало)
    return текст, текст != исходный


def правка_модуля(текст):
    if 'мвмЧастьВремениПриИзменении' in текст:
        return дополнить_выбор_по_складу(текст)
    for имя, строка, в_начало in ВСТАВКИ:
        текст = вставить_в_процедуру(текст, имя, строка, в_начало)
    # расчёт заполняет стоянки и раскладывает всё по полям
    было = '\tОбъект.Стоянка = Окр((Нормативы.Погрузка + Нормативы.Разгрузка) / 3600, 3);'
    if текст.count(было) != 1:
        sys.exit('ОШИБКА: в расчёте не найдено заполнение общей стоянки')
    текст = текст.replace(было, СТР.join([
        было,
        '\t// Стоянки по пунктам — главные поля расчёта, диспетчер смотрит на них.',
        '\tОбъект.СтоянкаПунктОтправления = Окр(Нормативы.Погрузка / 3600, 3);',
        '\tОбъект.СтоянкаПунктНазначения = Окр(Нормативы.Разгрузка / 3600, 3);']), 1)
    было = '\tмвмРазложитьВремяВПути();'
    if текст.count(было) != 1:
        sys.exit('ОШИБКА: не найден вызов мвмРазложитьВремяВПути')
    текст = текст.replace(было, было + СТР + '\tмвмРазложитьВремена();', 1)
    добавка = МОДУЛЬ.lstrip('\n').replace('\n', СТР)
    return текст.rstrip(СТР) + СТР + СТР + добавка, True


