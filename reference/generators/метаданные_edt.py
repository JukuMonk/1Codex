def ид():
    return str(uuid.uuid4())


def читать(путь):
    сырьё = open(путь, 'rb').read()
    if сырьё.startswith(b'\xef\xbb\xbf'):
        sys.exit(f'ОШИБКА: у {путь} BOM, в проекте EDT его быть не должно')
    if сырьё.count(b'\n') != сырьё.count(b'\r\n'):
        sys.exit(f'ОШИБКА: в {путь} есть одиночные LF')
    return сырьё.decode('utf-8')


def писать(путь, текст):
    if текст.count('\n') != текст.count('\r\n'):
        sys.exit(f'ОШИБКА: собранный {путь} не в CRLF')
    try:
        ET.fromstring(текст.encode('utf-8'))
    except ET.ParseError as e:
        sys.exit(f'ОШИБКА: {путь} не разбирается: {e}')
    if ПРОБА:
        return
    os.makedirs(os.path.dirname(путь), exist_ok=True)
    open(путь, 'wb').write(текст.encode('utf-8'))


def синоним(текст, отступ):
    о = ' ' * отступ
    return [f'{о}<synonym>', f'{о}  <key>ru</key>',
            f'{о}  <value>{текст}</value>', f'{о}</synonym>']


def тип_xml(описание, отступ):
    """«Строка(150)» / «Число(15,3)» / «Булево» / «Справочник.Имя» → <type>.

    Составной тип пишется через «|»: «Справочник.А|Справочник.Б». Такой тип
    бывает только у ссылок, поэтому квалификаторы к нему не применяются.
    """
    о = ' ' * отступ
    if '|' in описание:
        строки = [f'{о}<type>']
        for часть in описание.split('|'):
            вложенные = тип_xml(часть.strip(), отступ)
            строки += [с for с in вложенные if '<types>' in с]
        строки.append(f'{о}</type>')
        return строки
    строки = [f'{о}<type>']
    м = re.match(r'^Строка\((\d+)\)$', описание)
    if м:
        длина = int(м.group(1))
        if длина > 1024:
            sys.exit(f'ОШИБКА: строка длиннее 1024 ({описание}) — '
                     'обновление базы падает с «слишком большое значение '
                     'описателя длины». Для длинного текста ставь Строка(0).')
        строки.append(f'{о}  <types>String</types>')
        if длина == 0:
            строки.append(f'{о}  <stringQualifiers/>')       # неограниченная
        else:
            строки += [f'{о}  <stringQualifiers>',
                       f'{о}    <length>{длина}</length>',
                       f'{о}  </stringQualifiers>']
    elif re.match(r'^Число\(\d+,\d+\)$', описание):
        точность, дробь = re.findall(r'\d+', описание)
        строки += [f'{о}  <types>Number</types>',
                   f'{о}  <numberQualifiers>',
                   f'{о}    <precision>{точность}</precision>']
        if int(дробь):
            строки.append(f'{о}    <scale>{дробь}</scale>')
        строки.append(f'{о}  </numberQualifiers>')
    elif описание == 'Булево':
        строки.append(f'{о}  <types>Boolean</types>')
    elif описание == 'Дата':
        строки += [f'{о}  <types>Date</types>',
                   f'{о}  <dateQualifiers>',
                   f'{о}    <dateFractions>DateTime</dateFractions>',
                   f'{о}  </dateQualifiers>']
    elif описание.startswith('Справочник.'):
        строки.append(f'{о}  <types>CatalogRef.{описание.split(".", 1)[1]}</types>')
    elif описание.startswith('Перечисление.'):
        строки.append(f'{о}  <types>EnumRef.{описание.split(".", 1)[1]}</types>')
    elif описание.startswith('Документ.'):
        строки.append(f'{о}  <types>DocumentRef.{описание.split(".", 1)[1]}</types>')
    else:
        sys.exit(f'ОШИБКА: неизвестный тип «{описание}»')
    строки.append(f'{о}</type>')
    return строки


def реквизит(имя, подпись, тип, отступ, в_тч=False, обязательный=False):
    """Состав свойств у реквизита ТЧ МЕНЬШЕ, чем у реквизита шапки.

    Про это уже спотыкались на XML-выгрузке: 1С отвергала файл со словами
    «Свойство Use не входит в состав объекта метаданных Attribute». Здесь то
    же правило: у реквизита табличной части нет fillValue.
    """
    о = ' ' * отступ
    строки = [f'{о}<attributes uuid="{ид()}">', f'{о}  <name>{имя}</name>']
    строки += синоним(подпись, отступ + 2)
    строки += тип_xml(тип, отступ + 2)
    строки += [f'{о}  <minValue xsi:type="core:UndefinedValue"/>',
               f'{о}  <maxValue xsi:type="core:UndefinedValue"/>']
    # Порядок свойств в схеме .mdo: maxValue → fillChecking → fillValue.
    # Снят с живого образца (уатПунктыНазначения.ТипПункта), а не выдуман:
    # 1С отвергает файл, где значение уехало в соседний тег.
    if обязательный:
        строки.append(f'{о}  <fillChecking>ShowError</fillChecking>')
    if в_тч:
        строки += [f'{о}  <dataHistory>Use</dataHistory>',
                   f'{о}  <fullTextSearch>Use</fullTextSearch>']
    else:
        строки += [f'{о}  <fillValue xsi:type="core:UndefinedValue"/>',
                   f'{о}  <fullTextSearch>Use</fullTextSearch>',
                   f'{о}  <dataHistory>Use</dataHistory>']
    строки.append(f'{о}</attributes>')
    return строки


