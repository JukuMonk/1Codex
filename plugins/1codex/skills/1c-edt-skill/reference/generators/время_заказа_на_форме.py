def скрыть(текст, имя):
    """Спрятать элемент: строка <visible>true</visible> убирается — false
    у EDT умолчание, и он этот тег не пишет вовсе."""
    н, к = элемент(текст, имя)
    кусок = текст[н:к]
    строки = кусок.split(СТР)
    # Свой <visible> у элемента стоит на два пробела глубже его открывающего
    # тега; у группы — ПОСЛЕ всех детей, поэтому ищем по отступу, а не с начала.
    свой = ' ' * (отступ_строки(текст, н) + 2) + '<visible>'
    for i, с in enumerate(строки):
        if с.startswith(свой):
            del строки[i]
            break
    else:
        return текст
    return текст[:н] + СТР.join(строки) + текст[к:]


def родитель(текст, имя):
    """Имя элемента, в котором лежит элемент с этим именем: ближайший
    <name> на два пробела левее (имя родителя стоит раньше всех детей)."""
    i = текст.index('<name>%s</name>' % имя)
    отступ = отступ_строки(текст, i)
    for м in reversed(list(re.finditer(r'^( *)<name>([^<]+)</name>', текст[:i], re.M))):
        if len(м.group(1)) == отступ - 2:
            return м.group(2)
    sys.exit('ОШИБКА: у «%s» нет родителя' % имя)


def вырезать(текст, имя):
    """Убрать элемент целиком (вместе с переводом строки перед ним)."""
    if ('<name>%s</name>' % имя) not in текст:
        return текст
    н, к = элемент(текст, имя)
    н = текст.rfind(СТР, 0, н)
    return текст[:н] + текст[к:]


def обработчик_поля(сч_ничего, имя_поля, имя_обработчика):
    """Строки <handlers> для поля Ч/М/С."""
    return ['    <event>OnChange</event>', '    <name>%s</name>' % имя_обработчика]


def поле_с_обработчиком(сч, имя, подпись, отступ, обработчик):
    строки = поле_части(сч, имя, подпись, отступ)
    # обработчик — сразу за </dataPath>, как пишет EDT
    о = ' ' * отступ
    for i, с in enumerate(строки):
        if с == '%s  </dataPath>' % о:
            i += 1
            строки[i:i] = ['%s  <handlers>' % о,
                           '%s    <event>OnChange</event>' % о,
                           '%s    <name>%s</name>' % (о, обработчик),
                           '%s  </handlers>' % о]
            break
    return строки


