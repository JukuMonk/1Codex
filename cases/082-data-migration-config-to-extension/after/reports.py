# -*- coding: utf-8 -*-
"""Отчёты доработок через COM: настройки по умолчанию, период 2024–2026, результат — текст табличного документа.

  python tools/reports.py <база> [каталог]       # по файлу <отчёт>.txt на отчёт + сводка
Используется для сверки «ПРОД» и «поставка + расширение» на одних данных (tools/test_migration.py).
"""
import datetime
import os
import re
import sys
import tempfile

sys.stdout.reconfigure(encoding='utf-8')
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import com  # noqa: E402

UTC = datetime.timezone.utc
НАЧАЛО = datetime.datetime(2024, 1, 1, tzinfo=UTC)
# по 30.09.2026: КТГ и др. обрезают период текущим моментом — иначе сверка зависит от времени запуска
КОНЕЦ = datetime.datetime(2026, 9, 30, 23, 59, 59, tzinfo=UTC)
ОТЧЕТЫ = ['дс_АнализИспользованияПерсонала', 'дс_ПлановыеВнеплановыеРемонты', 'дс_ВозрастнойСоставОборудования',
          'дс_ПереченьОборудованияПоВидамПроизводств', 'торо_КТГОборудования', 'торо_ОстаткиНоменклатурыНаСкладах',
          'торо_ПланФактЗатрат', 'торо_СписокОборудования', 'торо_ИсторияИзмененияДатРемонта', 'торо_ПланФактТрудозатрат',
          'торо_ПланФактныйАнализРегламентныхМероприятий']


ОБЯЗАТЕЛЬНЫЕ_ССЫЛКИ = {'ГрафикРаботы': 'Справочник.Календари'}


def заполнить_параметры(cn, схема, настройки):
    """Параметры-даты и стандартные периоды схемы: период 2024–2026 (тип — по описанию типов параметра схемы)."""
    for п in схема.Параметры:
        имя = п.Имя
        тип = cn.String(п.ТипЗначения) if п.ТипЗначения is not None else ''
        if 'Стандартный период' in тип:
            сп = cn.NewObject('СтандартныйПериод')
            сп.ДатаНачала, сп.ДатаОкончания = НАЧАЛО, КОНЕЦ
            значение = сп
        elif тип == 'Дата':
            значение = НАЧАЛО if re.search(r'Начал', имя) else КОНЕЦ
        elif имя in ОБЯЗАТЕЛЬНЫЕ_ССЫЛКИ:
            # параметр-ссылка без значения по умолчанию (в форме его выбирает пользователь) — первый элемент
            з = cn.NewObject('Запрос')
            з.Текст = 'ВЫБРАТЬ ПЕРВЫЕ 1 Т.Ссылка КАК С ИЗ %s КАК Т УПОРЯДОЧИТЬ ПО Т.Наименование' % ОБЯЗАТЕЛЬНЫЕ_ССЫЛКИ[имя]
            в = з.Выполнить().Выбрать()
            if not в.Следующий():
                continue
            значение = в.С
        else:
            continue
        try:
            настройки.ПараметрыДанных.УстановитьЗначениеПараметра(имя, значение)
        except Exception:
            pass


def скомпоновать(cn, имя):
    отчет = getattr(cn.Отчеты, имя).Создать()
    схема = отчет.СхемаКомпоновкиДанных
    отчет.КомпоновщикНастроек.Инициализировать(cn.NewObject('ИсточникДоступныхНастроекКомпоновкиДанных', схема))
    отчет.КомпоновщикНастроек.ЗагрузитьНастройки(схема.НастройкиПоУмолчанию)
    # БСП 3.0.25: отчёты ТОИР читают ключ варианта из доп. свойств настроек (в форме его ставит БСП)
    if схема.ВариантыНастроек.Количество():
        отчет.КомпоновщикНастроек.Настройки.ДополнительныеСвойства.Вставить(
            'КлючПредопределенногоВарианта', схема.ВариантыНастроек.Получить(0).Имя)
    заполнить_параметры(cn, схема, отчет.КомпоновщикНастроек.Настройки)
    тд = cn.NewObject('ТабличныйДокумент')
    отчет.СкомпоноватьРезультат(тд, cn.NewObject('ДанныеРасшифровкиКомпоновкиДанных'))
    f = os.path.join(tempfile.gettempdir(), 'npcap_rep.txt')
    тд.Записать(f, cn.ТипФайлаТабличногоДокумента.TXT)
    with open(f, encoding='utf-8-sig', errors='replace') as h:
        txt = h.read()
    # строки с датой/временем формирования — не сравниваются
    txt = txt.replace('{НПЦАП_Доработки ', '{')
    return '\n'.join(l for l in txt.splitlines() if not re.search(r'\d\d\.\d\d\.\d{4} \d{1,2}:\d\d:\d\d', l))


def main(base, out=None):
    cn = com.connect(base)
    out = out or os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'logs', 'reports_' + base)
    os.makedirs(out, exist_ok=True)
    итог = {}
    for имя in ОТЧЕТЫ:
        try:
            txt = скомпоновать(cn, имя)
            with open(os.path.join(out, имя + '.txt'), 'w', encoding='utf-8') as f:
                f.write(txt)
            итог[имя] = 'строк %d' % len([l for l in txt.splitlines() if l.strip()])
        except Exception as e:
            # место ошибки в модуле расширения подписано «{НПЦАП_Доработки …}» — для сверки не важно
            итог[имя] = 'ОШИБКА ' + com.ошибка(e).replace('\n', ' ').replace('{НПЦАП_Доработки ', '{')[:400]
            with open(os.path.join(out, имя + '.txt'), 'w', encoding='utf-8') as f:
                f.write(итог[имя])
        print('  %-50s %s' % (имя, итог[имя]))
    return итог


if __name__ == '__main__':
    main(*sys.argv[1:])
