def отступ(текст, позиция):
    return база.отступ_строки(текст, позиция)


def внутри(текст, имя, куда):
    н, к = база.элемент(текст, имя)
    кн, кк = база.элемент(текст, куда)
    return кн < н < кк


def переместить(текст, имя, куда, перед=None):
    """Элемент — в группу «куда»: перед элементом «перед» или последним."""
    н, к = база.элемент(текст, имя)
    было = отступ(текст, н)
    начало_строки = текст.rfind(СТР, 0, н)
    кусок = ' ' * было + текст[н:к]
    текст = текст[:начало_строки] + текст[к:]
    кн, кк = база.элемент(текст, куда)
    надо = отступ(текст, кн) + 2
    сдвиг = надо - было
    строки = []
    for с in кусок.split(СТР):
        if сдвиг >= 0:
            строки.append((' ' * сдвиг + с) if с.strip() else с)
        else:
            строки.append(с[-сдвиг:] if с.startswith(' ' * -сдвиг) else с)
    if перед:
        пн, _ = база.элемент(текст, перед)
        i = текст.rfind(СТР, 0, пн) + len(СТР)
    else:
        # собственный <visible> группы стоит после всех детей на её отступе
        i = текст.index(СТР + ' ' * надо + '<visible>', кн) + len(СТР)
    return текст[:i] + СТР.join(строки) + СТР + текст[i:]


def показать(текст, имя):
    """Вернуть элементу <visible>true</visible>, если прежняя сборка убрала."""
    н, к = база.элемент(текст, имя)
    кусок = текст[н:к]
    свой = ' ' * (отступ(текст, н) + 2)
    if (СТР + свой + '<visible>') in кусок:
        return текст
    i = кусок.index(СТР + свой + '<enabled>')
    кусок = кусок[:i] + СТР + свой + '<visible>true</visible>' + кусок[i:]
    return текст[:н] + кусок + текст[к:]


def вернуть_типовую_раскладку(текст):
    """Прежняя сборка скрывала и переставляла прямо в XML — откатываем:
    этим теперь занимается модуль по константе."""
    изменено = False
    for имя in СКРЫТЬ:
        if ('<name>%s</name>' % имя) not in текст:
            continue
        новый = показать(текст, имя)
        изменено |= новый != текст
        текст = новый
    if внутри(текст, 'ГруппаДетализация', 'ГруппаДополнительно'):
        текст = переместить(текст, 'ГруппаДетализация', 'ГруппаПраваяКолонка',
                            перед='ГруппаОрганизация')
        изменено = True
    if внутри(текст, 'ГруппаВидДоставкиПрав', 'ГруппаДополнительно'):
        текст = переместить(текст, 'ГруппаВидДоставкиПрав', 'ГруппаВидДоставки')
        изменено = True
    return текст, изменено


