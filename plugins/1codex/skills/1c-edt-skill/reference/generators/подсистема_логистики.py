def нарисовать(размер):
    """Маршрут по трём точкам. Рисуем крупно и уменьшаем — края мягче."""
    from PIL import Image, ImageDraw
    К = 16                      # во столько раз крупнее рабочего размера
    Ш = размер * К
    и = Image.new('RGBA', (Ш, Ш), (0, 0, 0, 0))
    р = ImageDraw.Draw(и)

    ЛИНИЯ = (232, 150, 32, 255)     # янтарный — маршрут, как в самом АРМ
    УЗЕЛ = (58, 74, 92, 255)        # графитовый — обычный узел
    ЦЕЛЬ = (232, 150, 32, 255)      # конечная точка тем же янтарным

    # Точки в долях холста: снизу слева → вверх по диагонали → вправо вниз.
    точки = [(0.17, 0.80), (0.46, 0.23), (0.81, 0.58)]
    пикс = [(x * Ш, y * Ш) for x, y in точки]

    р.line(пикс, fill=ЛИНИЯ, width=int(Ш * 0.115), joint='curve')

    for (x, y), цвет, доля in zip(пикс, (УЗЕЛ, УЗЕЛ, ЦЕЛЬ),
                                  (0.125, 0.10, 0.15)):
        r = Ш * доля
        # Белая рубашка под кругом: иконка ложится и на тёмную панель.
        р.ellipse([x - r * 1.2, y - r * 1.2, x + r * 1.2, y + r * 1.2],
                  fill=(255, 255, 255, 235))
        р.ellipse([x - r, y - r, x + r, y + r], fill=цвет)

    return и.resize((размер, размер), Image.LANCZOS)


