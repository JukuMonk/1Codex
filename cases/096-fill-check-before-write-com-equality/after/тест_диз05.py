# -*- coding: utf-8 -*-
"""ДиЗ-05 к ТЗ-01 — проверки через COM в ПЕСОЧНИЦЕ (пишет данные: только песочница).

  python тесты/тест_диз05.py
п.1–3 метаданные (тип сценария, адрес объекта, справочник адресов с группами); п.4 черновик по типу сценария и
правилу; п.5 новая версия проходит проверку заполнения (наименование по шаблону, номер — следующий); п.6–7 версия-
маппинг с передающими / принимающими объектами и строками соответствий записывается и читается.
"""
import sys

sys.stdout.reconfigure(encoding='utf-8')
sys.path.insert(0, __file__.rsplit('тесты', 1)[0] + 'инструменты')
import платформа as пл  # noqa: E402

ИТОГ = []


def проверка(пункт, условие, что):
    ИТОГ.append((пункт, bool(условие), что))
    print('%s п.%s %s' % ('ОК  ' if условие else 'ОШИБКА', пункт, что))


def равно(cn, а, б):
    """Ссылки и значения перечислений через COM — разные объекты: сравнивать по XML-представлению."""
    return cn.XMLString(а) == cn.XMLString(б)


def первая(cn, текст, **параметры):
    q = cn.NewObject('Запрос')
    q.Text = текст
    for к, з in параметры.items():
        q.SetParameter(к, з)
    в = q.Execute().Select()
    return в.Ссылка if в.Next() else None


def main():
    cn = пл.com('песочница')
    Перечисления, Справочники = cn.Перечисления, cn.Справочники
    ПИ = Перечисления.ТипыСценариев.ПользовательскаяИстория
    ПР = Перечисления.ТипыСценариев.ПрограммнаяРазработка

    # п.3: справочник адресов с группами
    группа = Справочники.АдресаОбъектов.СоздатьГруппу()
    группа.Наименование = 'ТОИР / Оборудование (тест ДиЗ-05)'
    группа.Записать()
    адрес = Справочники.АдресаОбъектов.СоздатьЭлемент()
    адрес.Родитель = группа.Ссылка
    адрес.Наименование = 'Оборудование и нормативы / Оборудование / Марки, модели'
    адрес.Примечание = 'х' * 2000
    адрес.Записать()
    проверка(3, len(адрес.Ссылка.Примечание) == 2000 and равно(cn, адрес.Ссылка.Родитель, группа.Ссылка) and адрес.Ссылка.Код,
             'адрес с кодом, в группе, примечание 2000 символов')

    # п.1–2, п.4: сценарий с версией, где есть строки «Добавить / Изменить» с правилами
    версия = первая(cn, '''ВЫБРАТЬ ПЕРВЫЕ 1 С.ВерсияСтруктуры КАК Ссылка ИЗ Справочник.СценарииРаботы КАК С
        ГДЕ НЕ С.ПометкаУдаления И С.ВерсияСтруктуры.Реквизиты.ПравилоЗаполнения.СпособЗаполнения
            = ЗНАЧЕНИЕ(Перечисление.СпособыЗаполнения.Автоматический)
        И С.ВерсияСтруктуры.Реквизиты.ВидИзменения В (ЗНАЧЕНИЕ(Перечисление.ВидыИзмененияРеквизитов.Добавить),
            ЗНАЧЕНИЕ(Перечисление.ВидыИзмененияРеквизитов.Изменить))''')
    проверка(4, версия is not None, 'есть версия структуры с автоматическими правилами (данные для проверки)')
    шаги_пи = cn.МетодологТЗ.ШагиИзВерсииСтруктуры(версия, ПИ)
    шаги_пр = cn.МетодологТЗ.ШагиИзВерсииСтруктуры(версия, ПР)
    шаги_пусто = cn.МетодологТЗ.ШагиИзВерсииСтруктуры(версия)
    ок_вид, ок_текст, автоматических, ручных = True, True, 0, 0
    for i in range(шаги_пи.Количество()):
        ш = шаги_пи.Получить(i)
        способ = cn.String(ш.ПравилоЗаполнения.СпособЗаполнения) if ш.ПравилоЗаполнения else ''
        ожид = 'Программная разработка' if способ.startswith('Автоматический') else 'Пользовательская история'
        автоматических += ожид == 'Программная разработка'
        ручных += ожид != 'Программная разработка'
        if cn.String(ш.ВидПункта) != ожид:
            ок_вид = False
            print('   строка %d: вид %r, ожидался %r (способ %r)' % (i + 1, cn.String(ш.ВидПункта), ожид, способ))
        описание = (ш.ПравилоЗаполнения.Описание or '').strip() if ш.ПравилоЗаполнения else ''
        if описание and ш.ТекстПункта != описание:
            ок_текст = False
    проверка(4, ок_вид and автоматических and ручных,
             'пользовательская история: вид по правилу (программная разработка %d, пользовательская история %d)'
             % (автоматических, ручных))
    проверка(4, ок_текст, 'пользовательская история: текст пункта — описание правила заполнения')
    проверка(4, all(cn.String(шаги_пр.Получить(i).ВидПункта) == 'Программная разработка'
                    and шаги_пр.Получить(i).ТекстПункта == шаги_пусто.Получить(i).ТекстПункта
                    for i in range(шаги_пр.Количество())),
             'программная разработка: вид и текст как прежде (%d шагов)' % шаги_пр.Количество())

    сценарий = первая(cn, 'ВЫБРАТЬ ПЕРВЫЕ 1 С.Ссылка КАК Ссылка ИЗ Справочник.СценарииРаботы КАК С ГДЕ НЕ С.ПометкаУдаления')
    о = сценарий.ПолучитьОбъект()
    о.ТипСценария = ПР
    о.АдресОбъекта = адрес.Ссылка
    о.Записать()
    проверка(1, равно(cn, сценарий.ТипСценария, ПР), 'тип сценария записывается')
    проверка(2, равно(cn, сценарий.АдресОбъекта, адрес.Ссылка), 'адрес объекта записывается')

    # п.5: новая версия без наименования проходит проверку заполнения
    объект = первая(cn, '''ВЫБРАТЬ ПЕРВЫЕ 1 В1.Владелец КАК Ссылка ИЗ Справочник.ВерсииСтруктурыОбъектов КАК В1
        ГДЕ НЕ В1.ПометкаУдаления И В1.Проект <> ЗНАЧЕНИЕ(Справочник.Проекты.ПустаяСсылка)''')
    проект = первая(cn, '''ВЫБРАТЬ ПЕРВЫЕ 1 В1.Проект КАК Ссылка ИЗ Справочник.ВерсииСтруктурыОбъектов КАК В1
        ГДЕ В1.Владелец = &О И В1.Проект <> ЗНАЧЕНИЕ(Справочник.Проекты.ПустаяСсылка)''', О=объект)
    наибольший = первая(cn, '''ВЫБРАТЬ ПЕРВЫЕ 1 В1.Ссылка КАК Ссылка ИЗ Справочник.ВерсииСтруктурыОбъектов КАК В1
        ГДЕ В1.Владелец = &О УПОРЯДОЧИТЬ ПО В1.Номер УБЫВ''', О=объект).Номер
    нов = Справочники.ВерсииСтруктурыОбъектов.СоздатьЭлемент()
    нов.Владелец = объект
    нов.Проект = проект
    нов.ВидВерсии = Перечисления.ВидыВерсийСтруктуры.Проект
    заполнено = нов.ПроверитьЗаполнение()
    проверка(5, заполнено, 'проверка заполнения новой версии без наименования проходит')
    нов.Записать()
    ожид = '%s / версия %d / %s' % (cn.String(проект).strip(), int(наибольший) + 1, cn.String(объект).strip())
    проверка(5, нов.Ссылка.Наименование == ожид, 'наименование по шаблону: %r' % нов.Ссылка.Наименование)
    проверка(5, int(нов.Ссылка.Номер) == int(наибольший) + 1, 'номер версии — следующий: %d' % int(нов.Ссылка.Номер))

    # п.6–7: версия-маппинг
    другой = первая(cn, '''ВЫБРАТЬ ПЕРВЫЕ 1 В1.Ссылка КАК Ссылка ИЗ Справочник.ВерсииСтруктурыОбъектов КАК В1
        ГДЕ НЕ В1.ПометкаУдаления И В1.Владелец <> &О И В1.Реквизиты.Реквизит <> ЗНАЧЕНИЕ(Справочник.РеквизитыОбъектов.ПустаяСсылка)''',
                   О=объект)
    м = нов.Ссылка.ПолучитьОбъект()
    м.ЭтоМаппинг = True
    п1 = м.ПередающиеОбъекты.Добавить()
    п1.Объект, п1.Версия = другой.Владелец, другой
    п2 = м.ПринимающиеОбъекты.Добавить()
    п2.Объект, п2.Версия = объект, нов.Ссылка
    стр_версии = другой.Реквизиты.Получить(0)
    с = м.Маппинг.Добавить()
    с.ПередающаяВерсия, с.ПередающийРеквизит, с.ПередающийТип = другой, стр_версии.Реквизит, стр_версии.ТипЗначения
    с.ПринимающаяВерсия, с.Значения, с.Примечание = нов.Ссылка, 'Да → Истина', 'х' * 1000
    м.Записать()
    р = нов.Ссылка
    проверка(6, р.ЭтоМаппинг, '«Это маппинг» записывается')
    проверка(7, р.ПередающиеОбъекты.Количество() == 1 and р.ПринимающиеОбъекты.Количество() == 1
             and р.Маппинг.Количество() == 1 and len(р.Маппинг.Получить(0).Примечание) == 1000
             and равно(cn, р.Маппинг.Получить(0).ПередающийРеквизит, стр_версии.Реквизит),
             'стороны и строка маппинга записываются (примечание 1000 символов)')
    проверка(7, р.Наименование == ожид, 'у маппинга то же правило наименования')
    del cn
    ошибок = sum(1 for _, ок, _ in ИТОГ if not ок)
    print('\nпроверок %d, ошибок %d' % (len(ИТОГ), ошибок))
    return 1 if ошибок else 0


if __name__ == '__main__':
    sys.exit(main())
