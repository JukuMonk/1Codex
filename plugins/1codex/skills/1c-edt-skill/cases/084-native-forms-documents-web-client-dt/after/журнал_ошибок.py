# -*- coding: utf-8 -*-
"""Ошибки из журнала регистрации файловой базы через COM — то, что видел пользователь в веб- или тонком клиенте,
а снимки и проверки через COM не ловят (case 084: `XMLСтрока` на клиенте в веб-клиенте).

  python журнал_ошибок.py "C:\\Базы\\Demo" [с=2026-10-16T08:00:00] [пользователь=Администратор] [пароль=]

Печатает: время, пользователь, приложение (Веб-клиент / Тонкий клиент / Фоновое задание), комментарий — в нём
модуль и строка вида «{DataProcessor.X.Form.Форма.Form(257,79)}: …».
"""
import sys

import win32com.client


def ошибки(путь, с_iso='', пользователь='Администратор', пароль=''):
    строка = 'File="%s";' % путь + ('Usr="%s";Pwd="%s";' % (пользователь, пароль) if пользователь else '')
    cn = win32com.client.Dispatch('V83.COMConnector').Connect(строка)
    таблица = cn.NewObject('ТаблицаЗначений')
    отбор = cn.NewObject('Структура')
    отбор.Вставить('Уровень', cn.УровеньЖурналаРегистрации.Ошибка)
    if с_iso:
        # дата — через XMLЗначение с типом из ОписаниеТипов: datetime из Python pywin32 сдвигает на пояс
        тип = cn.NewObject('ОписаниеТипов', 'Дата').Типы().Get(0)
        отбор.Вставить('ДатаНачала', cn.XMLЗначение(тип, с_iso))
    cn.ВыгрузитьЖурналРегистрации(таблица, отбор)
    out = []
    for i in range(таблица.Количество()):
        r = таблица.Получить(i)
        out.append((cn.XMLString(r.Дата), r.ИмяПользователя, r.ПредставлениеПриложения, str(r.Комментарий)))
    return out


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8')
    а = sys.argv[1:]
    for дата, кто, где, текст in ошибки(а[0], а[1] if len(а) > 1 else '', а[2] if len(а) > 2 else 'Администратор',
                                         а[3] if len(а) > 3 else ''):
        print(дата, кто, где, '|', текст[:600])
