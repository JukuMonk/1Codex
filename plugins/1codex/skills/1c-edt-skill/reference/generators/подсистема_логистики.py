def собрать_картинку():
    папка = os.path.join(ИСХ, 'CommonPictures', КАРТИНКА)
    путь_zip = os.path.join(папка, 'Picture.zip')

    манифест = ['<?xml version="1.0" encoding="UTF-8" standalone="yes"?>',
                '<Picture>']
    for имя, размер, плотность in МАСШТАБЫ:
        манифест.append('\t<PictureVariant name="%s" screenDensity="%s"'
                        ' glyphWidth="%d" glyphHeight="%d"/>'
                        % (имя, плотность, размер, размер))
    манифест.append('\t<PictureVariant name="Picture.png"'
                    ' interfaceVariant="version8_2" screenDensity="ldpi"'
                    ' glyphWidth="16" glyphHeight="16"/>')
    манифест.append('</Picture>')
    текст_манифеста = '\ufeff' + '\r\n'.join(манифест) + '\r\n'

    if not ПРОБА:
        os.makedirs(папка, exist_ok=True)
        # Формат картинок хранится сжатым; порядок файлов — как у типовой.
        with zipfile.ZipFile(путь_zip, 'w', zipfile.ZIP_DEFLATED) as z:
            for имя, размер, _п in МАСШТАБЫ:
                буфер = io.BytesIO()
                нарисовать(размер).save(буфер, 'PNG', optimize=True)
                z.writestr(имя, буфер.getvalue())
            буфер = io.BytesIO()
            нарисовать(16).save(буфер, 'PNG', optimize=True)
            z.writestr('Picture.png', буфер.getvalue())
            z.writestr('manifest.xml', текст_манифеста.encode('utf-8'))

    мдо = ['<?xml version="1.0" encoding="UTF-8"?>',
           '<mdclass:CommonPicture xmlns:mdclass='
           '"http://g5.1c.ru/v8/dt/metadata/mdclass" uuid="%s">'
           % uuid_из(os.path.join(папка, КАРТИНКА + '.mdo')),
           '  <name>%s</name>' % КАРТИНКА,
           '  <synonym>',
           '    <key>ru</key>',
           '    <value>Раздел &quot;%s&quot;</value>' % СИНОНИМ,
           '  </synonym>',
           '</mdclass:CommonPicture>',
           '']
    записать(os.path.join(папка, КАРТИНКА + '.mdo'), '\r\n'.join(мдо))
    return len(МАСШТАБЫ) + 1


