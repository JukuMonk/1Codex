def проверить_состав(состав):
    """Каждый объект подсистемы обязан существовать на диске.

    Опечатка в имени иначе выясняется только при загрузке конфигурации, а
    это десятки минут.
    """
    папки = {'Enum': 'Enums', 'Catalog': 'Catalogs', 'Document': 'Documents',
             'InformationRegister': 'InformationRegisters',
             'DataProcessor': 'DataProcessors', 'Report': 'Reports',
             'CommonModule': 'CommonModules'}
    пропавшие = []
    for объект in состав:
        вид, имя = объект.split('.', 1)
        if вид not in папки:
            sys.exit(f'ОШИБКА: неизвестный вид объекта «{вид}» в составе')
        if not os.path.isdir(os.path.join(ИСХ, папки[вид], имя)):
            пропавшие.append(объект)
    if пропавшие:
        sys.exit('ОШИБКА: в конфигурации нет объектов: ' + ', '.join(пропавшие))


# ------------------------------------------------- доработка готового объекта
# Якоря привязаны к переводу строки НЕ ради красоты: без него «  </attributes>»
# совпадает и с четырёхпробельным закрытием внутри табличной части, и новые
# реквизиты уезжают в чужую таблицу. На этом уже спотыкались.
ЗАКР_РЕКВИЗИТОВ = СТР + '  </attributes>' + СТР
ЗАКР_ТЧ = СТР + '  </tabularSections>' + СТР


def доработать(о):
    путь = os.path.join(ИСХ, 'Catalogs', о['имя'], о['имя'] + '.mdo')
    текст = читать(путь)
    добавлено = []

    новые = [р for р in о.get('реквизиты', [])
             if f'<name>{р[0]}</name>' not in текст]
    if новые:
        блок = []
        for р in новые:
            блок += реквизит(р[0], р[1], р[2], 2,
                             обязательный=(len(р) > 3 and р[3] == 'обязательный'))
            добавлено.append('реквизит ' + р[0])
        текст = вставить_после_последнего(текст, ЗАКР_РЕКВИЗИТОВ, блок,
                                          'реквизиты')

    новые_тч = [т for т in о.get('табличныеЧасти', [])
                if f'<name>{т["имя"]}</name>' not in текст]
    if новые_тч:
        блок = []
        for т in новые_тч:
            блок += табличная_часть(о['имя'], т, 2)
            добавлено.append('ТЧ ' + т['имя'])
        # порядок в схеме: attributes → tabularSections → forms
        якорь = (ЗАКР_ТЧ if ЗАКР_ТЧ in текст else ЗАКР_РЕКВИЗИТОВ)
        текст = вставить_после_последнего(текст, якорь, блок, 'табличные части')

    if добавлено:
        писать(путь, текст)
    return добавлено


def вставить_после_последнего(текст, якорь, блок, что):
    поз = текст.rfind(якорь)
    if поз < 0:
        sys.exit(f'ОШИБКА: не найдено место для вставки ({что})')
    поз += len(якорь)
    return текст[:поз] + СТР.join(блок) + СТР + текст[поз:]


# ------------------------------------------------- регистрация в конфигурации
ГРУППЫ = {'Перечисление': ('enums', 'Enum', 'Enums'),
          'Подсистема': ('subsystems', 'Subsystem', 'Subsystems'),
          'ОбщийМодуль': ('commonModules', 'CommonModule', 'CommonModules'),
          'Справочник': ('catalogs', 'Catalog', 'Catalogs'),
          'РегистрСведений': ('informationRegisters', 'InformationRegister',
                              'InformationRegisters')}


def зарегистрировать(текст, вид, имя):
    тег, префикс, _ = ГРУППЫ[вид]
    строка = f'  <{тег}>{префикс}.{имя}</{тег}>'
    if строка + СТР in текст:
        return текст, False
    # встаём последними в своей группе: так же лёг мвмАРМДиспетчера
    последняя = текст.rfind(f'  <{тег}>')
    if последняя < 0:
        sys.exit(f'ОШИБКА: в Configuration.mdo нет группы <{тег}>')
    конец = текст.index(СТР, последняя) + len(СТР)
    return текст[:конец] + строка + СТР + текст[конец:], True


def main():
    print('Метаданные редактора графа и геозон%s'
          % ('   (ПРОБА)' if ПРОБА else ''))
    конфиг = читать(КОНФИГ)
    новых = 0

    for о in СПЕЦИФИКАЦИЯ:
        вид, имя = о['вид'], о['имя']
        if вид == 'ДоработкаСправочника':
            сделано = доработать(о)
            print('  %-24s %s' % (имя, ', '.join(сделано) if сделано
                                  else 'всё уже есть'))
            continue

        _, _, папка = ГРУППЫ[вид]
        путь = os.path.join(ИСХ, папка, имя, имя + '.mdo')
        если_есть = os.path.exists(путь)
        if не_надо(если_есть, имя):
            continue
        if вид == 'Подсистема':
            проверить_состав(о['состав'])
        текст = {'Перечисление': перечисление,
                 'Справочник': справочник,
                 'РегистрСведений': регистр_сведений,
                 'Подсистема': подсистема,
                 'ОбщийМодуль': общий_модуль}[вид](о)
        писать(путь, текст)
        конфиг, добавили = зарегистрировать(конфиг, вид, имя)
        новых += 1
        подробность = ''
        if вид == 'Перечисление':
            подробность = '%d значений' % len(о['значения'])
        elif вид == 'Справочник':
            подробность = '%d реквизитов' % len(о.get('реквизиты', []))
            if о.get('табличныеЧасти'):
                подробность += ', ТЧ %s' % ', '.join(
                    т['имя'] for т in о['табличныеЧасти'])
        elif вид == 'Подсистема':
            подробность = '%d объектов в составе' % len(о['состав'])
        elif вид == 'ОбщийМодуль':
            подробность = 'серверный, с вызовом сервера'
        else:
            подробность = '%d измерений, %d ресурсов' % (
                len(о['измерения']), len(о['ресурсы']))
        print('  %-24s %s%s' % (имя, подробность,
                                '' if добавили else ' (уже в конфигурации)'))

    писать(КОНФИГ, конфиг)
    print('  ---')
    print('  создано объектов: %d' % новых)


def не_надо(есть, имя):
    if есть:
        print('  %-24s уже существует — пропущен' % имя)
        return True
    return False


if __name__ == '__main__':
    main()
