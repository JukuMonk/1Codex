# -*- coding: utf-8 -*-
"""Постоянные тестовые данные ПЕСОЧНИЦЫ с меткой «ТЕСТ» (18.10.2026): сценарии нажатий и COM-тесты берут их
напрямую, без поиска подходящих данных (ДиЗ-05: два перезапуска — нужных сценариев в копии базы не было).
Идемпотентно: найдёт по наименованию или создаст; ссылки и навигационные ссылки — в .platform/тест_данные.json.

  python тесты/данные_песочницы.py          # создать / обновить, напечатать
  from данные_песочницы import подготовить  # {'сценарий_пи': {'ссылка', 'нав', 'имя'}, …}

Набор: сценарий «пользовательская история» без шагов (черновик из версии с ручными и автоматическими правилами);
сценарий «программная разработка» с пустым типом (выбор типа нажатиями); версия-маппинг (передающий и принимающий
объекты с версиями, строк соответствий нет — для «Загрузить все реквизиты»); адрес объекта в группе.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from помощники import КОРЕНЬ, com, первая  # noqa: E402

ФАЙЛ = os.path.join(КОРЕНЬ, '.platform', 'тест_данные.json')
МЕТКА = 'ТЕСТ'


def _сценарий(cn, имя, образец, тип):
    С = cn.Справочники
    сц = первая(cn, 'ВЫБРАТЬ С.Ссылка КАК Ссылка ИЗ Справочник.СценарииРаботы КАК С ГДЕ С.Наименование = &И', И=имя)
    о = сц.ПолучитьОбъект() if сц else С.СценарииРаботы.СоздатьЭлемент()
    for поле in ('Владелец', 'Участник', 'ЭлементПроцесса', 'Объект', 'ВерсияСтруктуры'):
        setattr(о, поле, getattr(образец, поле))
    о.Наименование = имя
    о.ТипСценария = тип
    о.Шаги.Очистить()
    о.Записать()
    return о.Ссылка


def подготовить():
    cn = com()
    С, П = cn.Справочники, cn.Перечисления
    нав = cn.ПолучитьНавигационнуюСсылку
    образец = первая(cn, '''ВЫБРАТЬ ПЕРВЫЕ 1 С.Ссылка КАК Ссылка ИЗ Справочник.СценарииРаботы КАК С
        ГДЕ НЕ С.ПометкаУдаления И НЕ С.Наименование ПОДОБНО "ТЕСТ%" И НЕ С.Наименование ПОДОБНО "%ДиЗ-05%"
        И С.ВерсияСтруктуры.Реквизиты.ПравилоЗаполнения.СпособЗаполнения
            = ЗНАЧЕНИЕ(Перечисление.СпособыЗаполнения.Автоматический)
        И С.ВерсияСтруктуры.Реквизиты.ВидИзменения В (ЗНАЧЕНИЕ(Перечисление.ВидыИзмененияРеквизитов.Добавить),
            ЗНАЧЕНИЕ(Перечисление.ВидыИзмененияРеквизитов.Изменить))''')
    пи = _сценарий(cn, МЕТКА + ' пользовательская история (черновик из версии)', образец,
                   П.ТипыСценариев.ПользовательскаяИстория)
    пр = _сценарий(cn, МЕТКА + ' программная разработка (тип выбирается)', образец, П.ТипыСценариев.ПустаяСсылка())

    группа = первая(cn, 'ВЫБРАТЬ А.Ссылка КАК Ссылка ИЗ Справочник.АдресаОбъектов КАК А ГДЕ А.ЭтоГруппа И А.Наименование = &И',
                    И=МЕТКА + ' адреса')
    if группа is None:
        г = С.АдресаОбъектов.СоздатьГруппу()
        г.Наименование = МЕТКА + ' адреса'
        г.Записать()
        группа = г.Ссылка
    адрес = первая(cn, 'ВЫБРАТЬ А.Ссылка КАК Ссылка ИЗ Справочник.АдресаОбъектов КАК А ГДЕ НЕ А.ЭтоГруппа И А.Наименование = &И',
                   И=МЕТКА + ' Оборудование и нормативы / Оборудование / Марки, модели')
    if адрес is None:
        а = С.АдресаОбъектов.СоздатьЭлемент()
        а.Родитель = группа
        а.Наименование = МЕТКА + ' Оборудование и нормативы / Оборудование / Марки, модели'
        а.Записать()
        адрес = а.Ссылка

    def объект_с_версией(шаблон):
        о_ = первая(cn, '''ВЫБРАТЬ ПЕРВЫЕ 1 В1.Владелец КАК Ссылка ИЗ Справочник.ВерсииСтруктурыОбъектов КАК В1
            ГДЕ В1.Владелец.Наименование ПОДОБНО &Ш И НЕ В1.ПометкаУдаления И НЕ В1.ЭтоМаппинг''', Ш=шаблон)
        return о_, (cn.МетодологТЗ.ВерсияСтруктурыПоУмолчанию(о_, С.ПроцессыBPMN.ПустаяСсылка()) if о_ else None)
    перед, перед_в = объект_с_версией('%Классы, подклассы%')
    прин, прин_в = объект_с_версией('%Марки, модели%')
    объект_м = первая(cn, '''ВЫБРАТЬ ПЕРВЫЕ 1 О.Ссылка КАК Ссылка ИЗ Справочник.ОбъектыКонфигурации КАК О
        ГДЕ О.Наименование ПОДОБНО "Маппинг%" УПОРЯДОЧИТЬ ПО О.Наименование''')
    м = первая(cn, 'ВЫБРАТЬ ПЕРВЫЕ 1 В1.Ссылка КАК Ссылка ИЗ Справочник.ВерсииСтруктурыОбъектов КАК В1 ГДЕ В1.Владелец = &О',
               О=объект_м)
    мо = м.ПолучитьОбъект() if м else С.ВерсииСтруктурыОбъектов.СоздатьЭлемент()
    мо.Владелец = объект_м
    мо.ВидВерсии = П.ВидыВерсийСтруктуры.Проект
    мо.Проект = первая(cn, 'ВЫБРАТЬ ПЕРВЫЕ 1 П.Ссылка КАК Ссылка ИЗ Справочник.Проекты КАК П ГДЕ П.Наименование ПОДОБНО "021.1.%"')
    мо.ЭтоМаппинг = True
    for тч in (мо.ПередающиеОбъекты, мо.ПринимающиеОбъекты, мо.Маппинг):
        тч.Очистить()
    с = мо.ПередающиеОбъекты.Добавить()
    с.Объект, с.Версия = перед, перед_в
    с = мо.ПринимающиеОбъекты.Добавить()
    с.Объект, с.Версия = прин, прин_в
    мо.Записать()

    def запись(ссылка):
        return {'нав': нав(ссылка), 'имя': cn.String(ссылка)}
    данные = {'сценарий_пи': запись(пи), 'сценарий_пр': запись(пр), 'маппинг': запись(мо.Ссылка),
              'адрес': запись(адрес), 'объект_для_версии': cn.String(прин).split(' (')[0][:30],
              'проект': '021.1'}
    del cn
    os.makedirs(os.path.dirname(ФАЙЛ), exist_ok=True)
    json.dump(данные, open(ФАЙЛ, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    return данные


if __name__ == '__main__':
    for к, з in подготовить().items():
        print('%-18s %s' % (к, з['имя'] if isinstance(з, dict) else з))
