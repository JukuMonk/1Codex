def описание_подсистемы(имя, синоним, пояснение, состав, дети=(),
                        картинка=None, в_интерфейсе=True, путь_mdo=None,
                        ид=None, родитель=None):
    """путь_mdo — откуда взять прежний uuid; ид — готовый uuid раздела."""
    строки = ['<?xml version="1.0" encoding="UTF-8"?>',
              '<mdclass:Subsystem'
              ' xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"'
              ' xmlns:core="http://g5.1c.ru/v8/dt/mcore"'
              ' xmlns:mdclass="http://g5.1c.ru/v8/dt/metadata/mdclass"'
              ' uuid="%s">'
              % (ид or uuid_из(путь_mdo)),
              '  <name>%s</name>' % имя,
              '  <synonym>',
              '    <key>ru</key>',
              '    <value>%s</value>' % синоним,
              '  </synonym>',
              '  <includeInCommandInterface>%s</includeInCommandInterface>'
              % ('true' if в_интерфейсе else 'false')]
    if пояснение:
        строки += ['  <explanation>',
                   '    <key>ru</key>',
                   '    <value>%s</value>' % пояснение,
                   '  </explanation>']
    if картинка:
        строки += ['  <picture xsi:type="core:PictureRef">',
                   '    <picture>CommonPicture.%s</picture>' % картинка,
                   '  </picture>']
    for объект in состав:
        строки.append('  <content>%s</content>' % объект)
    for ребёнок in дети:
        строки.append('  <subsystems>%s</subsystems>' % ребёнок)
    # Связь «кто чей» держит именно этот тег, а не вложенность папок: без него
    # EDT не считает подсистему дочерней и не выгружает её вовсе.
    if родитель:
        строки.append('  <parentSubsystem>Subsystem.%s</parentSubsystem>'
                      % родитель)
    строки += ['</mdclass:Subsystem>', '']
    return '\r\n'.join(строки)


def построить_подсистемы():
    корень = os.path.join(ИСХ, 'Subsystems')
    старая = os.path.join(корень, СТАРОЕ_ИМЯ)
    новая = os.path.join(корень, ИМЯ)

